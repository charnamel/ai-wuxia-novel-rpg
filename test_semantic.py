results = {"pass": 0, "fail": 0, "skip": 0}
details = []

for i, (category, subcategory, query, expected_titles, note) in enumerate(test_cases, 1):
    # 执行检索
    t0 = time.time()
    result_text = worldbook.search(query)
    search_time = time.time() - t0

    # 判断是否命中期望
    if expected_titles:
        hit = any(title in result_text for title in expected_titles)
    else:
        # expected_titles为None时，有结果即算通过
        hit = bool(result_text)

    status = "✅" if hit else "❌"
    results["pass" if hit else "fail"] += 1

    # 提取命中条目（简化显示）
    hit_items = []
    if result_text:
        for line in result_text.split("\n"):
            if line.startswith("【") and "】" in line:
                title = line.split("】")[0] + "】"
                if title not in hit_items:
                    hit_items.append(title)

    detail = {
        "id": i,
        "category": category,
        "subcategory": subcategory,
        "query": query,
        "expected": expected_titles,
        "hit": hit,
        "time_ms": search_time * 1000,
        "hit_items": hit_items[:5],
        "result_len": len(result_text),
        "note": note,
    }
    details.append(detail)

    # 打印结果
    print(f"{status} [{i:02d}] {category}/{subcategory}: '{query}'")
    print(f"     期望: {expected_titles or '有结果即可'}")
    if hit_items:
        print(f"     命中: {', '.join(hit_items[:5])}")
    else:
        print(f"     命中: (空)")
    print(f"     耗时: {search_time*1000:.0f}ms | 结果: {len(result_text)}字")
    print()


# ========== 汇总报告 ==========
