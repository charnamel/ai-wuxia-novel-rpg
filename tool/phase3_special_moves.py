# 已使用过的特技名（避免重复）
used_names = set()
for v in arts.values():
    if v.get('special_move_name'):
        used_names.add(v['special_move_name'])

import random
random.seed(42)  # 固定种子，确保可复现

count = 0
for name, art in arts.items():
    if not art.get('effect'):
        continue
    if art.get('special_move_name'):
        continue  # 已有特技名，跳过
    
    effect = art.get('effect', {})
    etype = effect.get('type', 'external_wound')
    patterns = EFFECT_PATTERNS.get(etype, EFFECT_PATTERNS['external_wound'])
    
    # 选择未使用过的特技名
    available = [(n, d) for n, d in patterns if n not in used_names]
    if not available:
        available = patterns  # 实在没有就用重复的
    
    mn, md = random.choice(available)
    used_names.add(mn)
    
    art['special_move_name'] = mn
    art['special_move_desc'] = md
    count += 1

